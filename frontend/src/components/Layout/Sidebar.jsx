const Sidebar = () => {
  const { doctor, logout } = useAuth();
  const navigate = useNavigate();

  const handleLogout = () => {
    logout();
    navigate('/login');
  };

  const getInitials = (name) => {
    if (!name) return 'DR';
    return name.split(' ').map(n => n[0]).join('').toUpperCase().slice(0, 2);
  };

  const navItems = [
    { to: '/dashboard', icon: icons.dashboard, label: 'Dashboard' },
    { to: '/patients', icon: icons.patients, label: 'Patients' },
    { to: '/scan-analysis', icon: icons.scan, label: 'Scan Analysis' },
    { to: '/reports', icon: icons.reports, label: 'Reports' },
    { to: '/profile', icon: icons.profile, label: 'Profile' },
    { to: '/settings', icon: icons.settings, label: 'Settings' },
  ];

  return (
    <aside className="sidebar">
      <div className="sidebar-brand">
        <h1>
          <span className="brand-icon">NS</span>
          NeuroScan AI
        </h1>
        <p>Explainable MRI Assist</p>
      </div>

      <nav className="sidebar-nav">
        {navItems.map((item) => (
          <NavLink
            key={item.to}
            to={item.to}
            className={({ isActive }) =>
              `nav-item ${isActive ? 'active' : ''}`
            }
          >
            <span className="nav-icon">{item.icon}</span>
            {item.label}
          </NavLink>
        ))}
      </nav>

      <div className="sidebar-footer">
        <div className="sidebar-user">
          <div className="sidebar-avatar">
            {getInitials(doctor?.name)}
          </div>
          <div className="sidebar-user-info">
            <div className="user-name">
              Dr. {doctor?.name || 'Doctor'}
            </div>
            <div className="user-role">
              {doctor?.specialization || 'Neuroscientist'}
            </div>
          </div>
        </div>
        <button className="sidebar-logout" onClick={handleLogout}>
          <span className="nav-icon">{icons.logout}</span>
          Logout
        </button>
      </div>
    </aside>
  );
};

export default Sidebar;
